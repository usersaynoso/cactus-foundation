#!/usr/bin/env node
import { writeFileSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'
import { getModuleNames } from './lib/module-names.mjs'
import { findDirectKeyReaders } from './lib/encryption-key-readers.mjs'

// Which installed modules still read ENCRYPTION_KEY straight from the environment,
// for the encryption key rotation screen to refuse on (see
// scripts/lib/encryption-key-readers.mjs for why). Worked out from the module
// code actually in this build, so updating a module clears it with no list to keep.

const __dirname = dirname(fileURLToPath(import.meta.url))
const rootDir = join(__dirname, '..')
const outPath = join(rootDir, 'lib', 'modules', 'encryption-key-readers.ts')

const readers = []
for (const name of getModuleNames(rootDir)) {
  const files = findDirectKeyReaders(join(rootDir, 'modules', name))
  if (files.length > 0) readers.push({ module: name, files })
}

const out = [
  '// AUTO-GENERATED by scripts/generate-module-key-readers.mjs',
  '// DO NOT EDIT BY HAND. Rewritten on every build and dev start.',
  '',
  '/** Installed modules that still read ENCRYPTION_KEY directly, and where. */',
  'export const modulesReadingEncryptionKeyDirectly: ReadonlyArray<{ module: string; files: readonly string[] }> = [',
  ...readers.map((r) => `  { module: ${JSON.stringify(r.module)}, files: ${JSON.stringify(r.files)} },`),
  ']',
  '',
]
writeFileSync(outPath, out.join('\n'))
console.log(
  `[generate-module-key-readers] encryption-key-readers.ts written (${readers.length} module(s) reading the key directly${readers.length ? `: ${readers.map((r) => r.module).join(', ')}` : ''})`,
)
