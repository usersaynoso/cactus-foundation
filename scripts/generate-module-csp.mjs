#!/usr/bin/env node
/**
 * Collects `cspOrigins` from every installed module's cactus.module.json and emits
 * the gitignored lib/modules/csp-origins.ts, which proxy.ts unions into the site's
 * Content-Security-Policy.
 *
 * Same pattern as generate-module-cron.mjs: the point is that no supplier hostname
 * belonging to a module ever gets written into a committed core file. A payment SDK
 * that draws its card fields in its own iframes simply cannot load under core's
 * default policy, and before this the only ways round it were naming that supplier
 * in core (which no module may do) or asking the site owner to fill in
 * CSP_EXTRA_ORIGINS by hand before their checkout would take a card.
 *
 * Validated here as well as in the manifest schema, because this file is what
 * actually reaches the browser's policy: only the seven fetch directives below,
 * only https origins, at most one leading "*." label. Nothing a module declares can
 * add a keyword ('unsafe-eval'), reach a plain-http host, or touch
 * frame-ancestors / base-uri / form-action.
 */

import { existsSync, readFileSync, writeFileSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'
import { getModuleNames as registeredModuleNames } from './lib/module-names.mjs'

const __dirname = dirname(fileURLToPath(import.meta.url))
const rootDir = join(__dirname, '..')
const modulesDir = join(rootDir, 'modules')
const outPath = join(rootDir, 'lib', 'modules', 'csp-origins.ts')

// Fetch directives a module may contribute to. Deliberately not the whole of CSP.
const DIRECTIVES = ['script', 'style', 'img', 'font', 'connect', 'frame', 'media']

const ORIGIN_RE = /^https:\/\/(\*\.)?[a-z0-9-]+(\.[a-z0-9-]+)+(:\d+)?$/i

// Registry-filtered: see scripts/lib/module-names.mjs for why a bare directory
// listing is not good enough here.
function getModuleNames() {
  return registeredModuleNames(rootDir)
}

const collected = Object.fromEntries(DIRECTIVES.map((d) => [d, new Set()]))

for (const moduleName of getModuleNames()) {
  const manifestPath = join(modulesDir, moduleName, 'cactus.module.json')
  if (!existsSync(manifestPath)) continue

  let manifest
  try {
    manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
  } catch {
    console.warn(`[generate-module-csp] Could not parse ${manifestPath} - skipping`)
    continue
  }

  const declared = manifest.cspOrigins
  if (!declared || typeof declared !== 'object' || Array.isArray(declared)) continue

  for (const [directive, origins] of Object.entries(declared)) {
    if (!DIRECTIVES.includes(directive)) {
      console.warn(`[generate-module-csp] ${moduleName} asked for unknown directive "${directive}" - ignored`)
      continue
    }
    if (!Array.isArray(origins)) {
      console.warn(`[generate-module-csp] ${moduleName} cspOrigins.${directive} is not a list - ignored`)
      continue
    }
    for (const raw of origins) {
      const origin = typeof raw === 'string' ? raw.trim().replace(/\/$/, '') : ''
      if (!ORIGIN_RE.test(origin)) {
        console.warn(`[generate-module-csp] ${moduleName} asked for "${raw}" on ${directive}-src - ignored (https origins only)`)
        continue
      }
      collected[directive].add(origin)
    }
  }
}

// Sorted so the generated file (and the header it produces) is stable between
// builds that installed the same modules in a different order.
const entries = DIRECTIVES.map((d) => [d, [...collected[d]].sort()])
const total = entries.reduce((n, [, list]) => n + list.length, 0)

const body = entries
  .map(([directive, list]) => `  ${directive}: [${list.map((o) => JSON.stringify(o)).join(', ')}],`)
  .join('\n')

writeFileSync(
  outPath,
  `// AUTO-GENERATED by scripts/generate-module-csp.mjs
// DO NOT EDIT BY HAND. Rewritten on every build and dev start.
//
// External origins the installed modules declared in their manifests, per CSP
// fetch directive. proxy.ts unions these into the site's own policy.

export type ModuleCspDirective = 'script' | 'style' | 'img' | 'font' | 'connect' | 'frame' | 'media'

export const moduleCspOrigins: Record<ModuleCspDirective, string[]> = {
${body}
}
`
)

console.log(
  `[generate-module-csp] lib/modules/csp-origins.ts written (${total} origin(s)${
    total > 0 ? `: ${entries.filter(([, l]) => l.length > 0).map(([d, l]) => `${d}-src ${l.join(' ')}`).join('; ')}` : ''
  })`
)
