#!/usr/bin/env node
/**
 * Collects `cacheBypassCookies` from every installed module's cactus.module.json
 * and emits the gitignored lib/modules/cache-cookies.ts, which lib/cache/page-cache.ts
 * unions with core's own session cookies.
 *
 * Same pattern, and same reason, as generate-module-csp.mjs: a cookie name that
 * belongs to a module must never be written into a committed core file. The shop's
 * basket cookie is the obvious case - a page cached while a shopper is carrying a
 * basket is a page that could be handed to the next shopper - and core cannot be
 * the place that knows the shop calls it cactus_shop_cart_id.
 *
 * A module declaring nothing here costs nothing: the page cache is off by default,
 * and when it is on, core's own session cookies are still always honoured.
 *
 * Validated here as well as in the manifest schema, because this list decides
 * whether somebody's personal page gets shared: cookie names only, matching the
 * characters RFC 6265 allows in a cookie name, and nothing else.
 */

import { existsSync, readFileSync, writeFileSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'
import { getModuleNames as registeredModuleNames } from './lib/module-names.mjs'

const __dirname = dirname(fileURLToPath(import.meta.url))
const rootDir = join(__dirname, '..')
const modulesDir = join(rootDir, 'modules')
const outPath = join(rootDir, 'lib', 'modules', 'cache-cookies.ts')

// RFC 6265 token characters, minus the separators. Deliberately strict - a name
// with a comma or a space in it is a typo, and a silently accepted typo here is
// a bypass that never fires.
const COOKIE_NAME_RE = /^[A-Za-z0-9!#$%&'*+._|~^-]+$/

// Registry-filtered: see scripts/lib/module-names.mjs for why a bare directory
// listing is not good enough here.
function getModuleNames() {
  return registeredModuleNames(rootDir)
}

const collected = new Set()

for (const moduleName of getModuleNames()) {
  const manifestPath = join(modulesDir, moduleName, 'cactus.module.json')
  if (!existsSync(manifestPath)) continue

  let manifest
  try {
    manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
  } catch {
    console.warn(`[generate-module-cache-cookies] Could not parse ${manifestPath} - skipping`)
    continue
  }

  const declared = manifest.cacheBypassCookies
  if (!declared) continue
  if (!Array.isArray(declared)) {
    console.warn(`[generate-module-cache-cookies] ${moduleName} cacheBypassCookies is not a list - ignored`)
    continue
  }

  for (const raw of declared) {
    const name = typeof raw === 'string' ? raw.trim() : ''
    if (!COOKIE_NAME_RE.test(name)) {
      console.warn(`[generate-module-cache-cookies] ${moduleName} asked for "${raw}" - ignored (cookie names only)`)
      continue
    }
    collected.add(name)
  }
}

// Sorted so the generated file is stable between builds that installed the same
// modules in a different order.
const names = [...collected].sort()

writeFileSync(
  outPath,
  `// AUTO-GENERATED by scripts/generate-module-cache-cookies.mjs
// DO NOT EDIT BY HAND. Rewritten on every build and dev start.
//
// Cookies the installed modules declared as "a request carrying this is
// personal". lib/cache/page-cache.ts adds these to core's own session cookies;
// a public page request carrying any of them is never made shareable.

export const moduleCacheBypassCookies: string[] = [${names.map((n) => JSON.stringify(n)).join(', ')}]
`
)

console.log(
  `[generate-module-cache-cookies] lib/modules/cache-cookies.ts written (${names.length} cookie(s)${
    names.length > 0 ? `: ${names.join(', ')}` : ''
  })`
)
