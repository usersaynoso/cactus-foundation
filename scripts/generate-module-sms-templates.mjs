#!/usr/bin/env node
import { existsSync, readFileSync, writeFileSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'
import { getModuleNames as registeredModuleNames } from './lib/module-names.mjs'

// Collects each module's `smsTemplates` manifest entry into one map core's text
// message registry can read. Exactly the email-templates generator one channel
// over: the module's own file supplies the defaults, core supplies the editor
// and the transport.
//
// Whether a module is *installed* is a database fact and is not decided here -
// the build clones every module in modules.json. The admin list filters by
// installed module before showing anything.

const __dirname = dirname(fileURLToPath(import.meta.url))
const rootDir = join(__dirname, '..')
const modulesDir = join(rootDir, 'modules')
const outPath = join(rootDir, 'lib', 'modules', 'sms-templates.ts')

const moduleNames = registeredModuleNames(rootDir)
const imports = []
const entries = []

for (const moduleName of moduleNames) {
  const manifestPath = join(modulesDir, moduleName, 'cactus.module.json')
  if (!existsSync(manifestPath)) continue

  let manifest
  try {
    manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
  } catch {
    console.warn(`[generate-module-sms-templates] Could not parse ${manifestPath} — skipping`)
    continue
  }

  const entry = manifest.smsTemplates
  if (!entry) continue
  if (!entry.groupLabel || !entry.import || !entry.export) {
    console.warn(`[generate-module-sms-templates] Invalid smsTemplates entry in ${moduleName} — skipping`)
    continue
  }

  const importPath = entry.import.replace(/^\.\//, `@/modules/${moduleName}/`)
  const safeModule = moduleName.replace(/-/g, '_')
  const ident = `_${safeModule}_${entry.export}`

  imports.push(`import { ${entry.export} as ${ident} } from '${importPath}'`)
  entries.push(
    `  ${JSON.stringify(moduleName)}: { groupLabel: ${JSON.stringify(entry.groupLabel)}, templates: ${ident} },`,
  )
}

const out = []
out.push(`// AUTO-GENERATED by scripts/generate-module-sms-templates.mjs`)
out.push(`// DO NOT EDIT BY HAND. Rewritten on every build and dev start.`)
out.push(``)
out.push(`import type { SmsTemplateDef } from '@/lib/sms/registry'`)
for (const imp of imports) out.push(imp)
out.push(``)
out.push(`export const moduleSmsTemplates: Record<string, { groupLabel: string; templates: SmsTemplateDef[] }> = {`)
for (const e of entries) out.push(e)
out.push(`}`)

writeFileSync(outPath, out.join('\n') + '\n')
console.log(
  `[generate-module-sms-templates] sms-templates.ts written (${entries.length} module(s): ${entries.map((e) => e.match(/^\s*"([^"]+)"/)?.[1]).filter(Boolean).join(', ') || 'none'})`,
)
